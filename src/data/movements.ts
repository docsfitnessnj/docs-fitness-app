export function getMovementById(id: string): Movement | undefined {
  return MOVEMENTS.find((m) => m.id === id);
}

// Matches the vault's search bar against name, original title, and cues
// (so searching a cue term surfaces every movement that mentions it once
// cues are filled in, and the raw title stays searchable too).
export function searchMovements(query: string): Movement[] {
  const q = query.trim().toLowerCase();
  if (!q) return MOVEMENTS;
  return MOVEMENTS.filter(
    (m) =>
      m.name.toLowerCase().includes(q) ||
      m.originalTitle.toLowerCase().includes(q) ||
      m.cues.some((c) => c.toLowerCase().includes(q))
  );
}
