export function deckCardLabel(card: DeckCardData): string {
  if (card.joker) return 'JOKER';
  return `${card.rank}${card.suit}`;
}

export function isRedSuit(suit?: DeckSuit): boolean {
  return suit === '♥' || suit === '♦';
}
